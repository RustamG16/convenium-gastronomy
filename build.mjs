// Convenium · Gastronomie — build. Usage: node build.mjs
// Renders DE (/) and EN (/en/) pages plus the four legal pages from content/*.json, computes the CSP hash of
// the one inline script, checks the colour pairs the design relies on, and verifies that every referenced
// asset exists. It writes only the named HTML files and .htaccess; styles.css, script.js and campaign.js are
// authored directly at the root.
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderPage, INLINE, csp } from './src/render.mjs';
import { renderLegal } from './src/legal.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = async (p) => JSON.parse(await readFile(path.join(root, p), 'utf8'));
const exists = (p) => access(path.join(root, p)).then(() => true, () => false);
const [de, en, camp, launch] = await Promise.all(['content/de.json', 'content/en.json', 'content/campaign.json', 'content/launch.json'].map(read));
const hash = createHash('sha256').update(INLINE).digest('base64');
const updated = '2026-10-22';
const errors = [];

// --- the colour pairs the page uses, measured (WCAG relative luminance) ---
const lum = (hex) => { const v = hex.replace('#', '').match(/../g).map((h) => parseInt(h, 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)); return 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const T = { noir: '#1B1717', cotton: '#EDEBDD', paper: '#F5F3E8', ink: '#241F1F', gray: '#6E6963', grayNoir: '#A8A29A', cherry: '#810100', maroon: '#630000', chili: '#D73B3E', chili300: '#E5595C', blush: '#E4D8CB', oxblood: '#460909', rose: '#CFA99F' };
const PAIRS = [
  ['ink', 'cotton', 4.5], ['ink', 'paper', 4.5], ['gray', 'cotton', 4.5], ['gray', 'paper', 4.5], ['cherry', 'cotton', 4.5], ['cherry', 'paper', 4.5],
  ['ink', 'blush', 4.5], ['cherry', 'blush', 4.5], ['cotton', 'cherry', 4.5], ['rose', 'cherry', 4.5], ['cotton', 'maroon', 4.5], ['cotton', 'oxblood', 4.5],
  ['chili300', 'oxblood', 4.5], ['cotton', 'noir', 4.5], ['grayNoir', 'noir', 4.5], ['chili300', 'noir', 4.5], ['chili', 'noir', 3]
];
for (const [fg, bg, min] of PAIRS) { const r = ratio(T[fg], T[bg]); if (r < min) errors.push(`contrast ${fg} on ${bg} = ${r.toFixed(2)} < ${min}`); }

// --- content parity: every DE key path exists in EN with the same shape ---
const shape = (o) => (Array.isArray(o) ? 'array' : o && typeof o === 'object' ? Object.fromEntries(Object.keys(o).sort().map((k) => [k, shape(o[k])])) : typeof o);
if (JSON.stringify(shape(de)) !== JSON.stringify(shape(en))) errors.push('de.json and en.json differ in shape');
for (const p of camp.packages) for (const c of [de, en]) if (!c.menu.items[p.id]) errors.push(`${c.lang}: menu.items.${p.id} missing`);
if (camp.packages.length !== 3) errors.push('three courses are the layout');
const sum = (ids) => ids.reduce((s, id) => s + camp.services[id].launch, 0);
for (const p of camp.packages) if (sum(p.services) !== p.launch) errors.push(`package ${p.id}: launch ${p.launch} != sum of services ${sum(p.services)}`);

// --- assets ---
for (const f of ['assets/savra/cover.jpg', 'assets/savra/cover-portrait.jpg', 'assets/savra/loop.mp4', 'assets/savra/loop-portrait.mp4', ...Array.from({ length: 175 }, (_, i) => `assets/seq/hero/${String(i + 1).padStart(4, '0')}.webp`), ...['d3-cherries', 'd3-plate', 'd3-fork', 'd3-glass', 'arch-bar', 'course-1', 'course-2', 'course-3', 'food-1', 'food-2', 'food-3', 'food-4', 'chef', 'cut-cherries', 'cut-glass', 'cut-cup'].map((n) => `assets/photos/${n}.webp`), 'assets/kit/fonts/instrument-serif-400.woff2', 'assets/kit/fonts/archivo-900.woff2', 'assets/kit/vendor/gsap.min.js', 'assets/kit/vendor/ScrollTrigger.min.js', 'assets/kit/fonts/fonts.css', 'favicon.svg', 'og.jpg', 'styles.css', 'script.js', 'campaign.js'])
  if (!(await exists(f))) errors.push(`missing ${f}`);

if (errors.length) { console.error('build refused:\n  ' + errors.join('\n  ')); process.exit(1); }

const pages = [
  ['index.html', renderPage({ c: de, camp, base: '', hash, launch, example: launch.example })],
  ['en/index.html', renderPage({ c: en, camp, base: '../', hash, launch, example: launch.example })],
  ['impressum/index.html', renderLegal({ kind: 'imprint', lang: 'de', launch, base: '../', other: '../en/imprint/', updated })],
  ['datenschutz/index.html', renderLegal({ kind: 'privacy', lang: 'de', launch, base: '../', other: '../en/privacy/', updated })],
  ['en/imprint/index.html', renderLegal({ kind: 'imprint', lang: 'en', launch, base: '../../', other: '../../impressum/', updated })],
  ['en/privacy/index.html', renderLegal({ kind: 'privacy', lang: 'en', launch, base: '../../', other: '../../datenschutz/', updated })],
  ['.htaccess', `# GENERATED by build.mjs. Inherits everything else from the studio root .htaccess.\n<IfModule mod_headers.c>\n  Header always unset Content-Security-Policy\n  Header always set Content-Security-Policy-Report-Only "${csp(hash)}; frame-ancestors 'none'"\n</IfModule>\n`],
  ['robots.txt', 'User-agent: *\nDisallow: /\n']
];
for (const [file, html] of pages) { await mkdir(path.dirname(path.join(root, file)), { recursive: true }); await writeFile(path.join(root, file), html); }
console.log(`built ${pages.length} files · inline hash sha256-${hash}`);
